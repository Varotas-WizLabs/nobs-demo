import { labelLanguage, registerStrings, t } from "./i18n.js?v=cd9defe92d";

/** t() with {name} placeholders filled from `vars`. */
export function th(key, vars = {}, lang = "ru") {
  return t(key, lang).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** Russian plural form: one (1, 21), few (2-4, 22-24) or many. */
export function ruPlural(n) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return "many";
  if (b === 1) return "one";
  if (b >= 2 && b <= 4) return "few";
  return "many";
}

/** A counted noun: "1 claim", "5 claims" / "1 утверждение", "5 утверждений". */
export function counted(n, base, lang = "ru") {
  const form = String(labelLanguage(lang) ?? "ru").startsWith("ru") ? ruPlural(n) : n === 1 ? "one" : "many";
  return th(`${base}.${form}`, { n }, lang);
}


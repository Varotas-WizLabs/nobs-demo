function baseLanguage(lang) {
  return String(lang ?? "en").split("-")[0].toLowerCase();
}

export function t(key, lang) {
  const table = STRINGS[baseLanguage(lang)] ?? STRINGS.en;
  return table[key] ?? STRINGS.en[key] ?? key;
}

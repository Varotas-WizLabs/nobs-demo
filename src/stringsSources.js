import { labelLanguage, registerStrings, t } from "./i18n.js?v=71d330228d";

/** t() with {name} placeholders filled from `vars`. */
export function tf(key, vars = {}, lang = "ru") {
  return t(key, lang).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** t() for a key built from a data value; `fallback` when no label exists. */
export function tl(key, fallback, lang = "ru") {
  const s = t(key, lang);
  return s === key ? fallback : s;
}


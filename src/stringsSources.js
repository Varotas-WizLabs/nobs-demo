const isEnglish = () => labelLanguage("ru") === "en";

/** A fixed server text by its stable key: English in English mode when a
 * translation exists, otherwise the server's own text unchanged. */
export function serverText(key, original) {
  if (!isEnglish() || !Object.hasOwn(SERVER_EN, key)) return original;
  return SERVER_EN[key];
}

/** A topic's label: `id` from routing.py TOPICS, `label` as the server sent it. */
export function topicLabel(id, label) {
  return serverText(`srcui.topic.${id}`, label || id);
}

/** One field of a connector (specs.py), e.g. connText(c, "bias"). */
export function connText(c, field, value = c?.[field]) {
  return serverText(`trustui.conn.${c?.id ?? c?.connector}.${field}`, value);
}


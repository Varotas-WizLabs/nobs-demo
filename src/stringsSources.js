const SIGNAL_EN = [
  [/^в списке недостоверных сайтов$/, () => "on the list of unreliable sites"],
  [/^нет снимков в архиве$/, () => "no captures in the archive"],
  [
    /^первый снимок (\S+) \(([\d.]+) г\.\)( — молодой домен)?$/,
    (m) => `first capture ${m[1]} (${m[2]} yr)${m[3] ? " — young domain" : ""}`,
  ],
  [/^(\d+) утверждений, (\d+) фактчеков$/, (m) => `${m[1]} claims, ${m[2]} fact-checks`],
  [/^угроза: (.*)$/, (m) => `threat: ${m[1]}`],
  [/^угроз не найдено$/, () => "no threats found"],
  [
    /^(\d+) \/ 100 \((\d+) исп\., уверенность (\w+)\)$/,
    (m) => `${m[1]} / 100 (${m[2]} uses, confidence ${tl(`srcui.conf.${m[3]}`, m[3], "en")})`,
  ],
];

/** A trust signal's label in the interface language (known templates only). */
export function signalLabel(label) {
  if (!isEnglish() || typeof label !== "string") return label;
  const rsp = label.match(/^(.*?)(?: \(зависит от темы: (.*)\))?$/);
  if (rsp && Object.hasOwn(RSP_EN, rsp[1])) return `${RSP_EN[rsp[1]]}${rsp[2] ? ` (depends on the topic: ${rsp[2]})` : ""}`;
  for (const [re, fn] of SIGNAL_EN) {
    const m = label.match(re);
    if (m) return fn(m);
  }
  return label;
}
